// The text of strings.conceptPanel in every shape the debrief draws (debrief-view.js, ENG-09b): a
// string, one { heading?, text } object, or an array of them. Reading `.text` alone saw nothing in
// an array panel, so checks on array panels passed without looking.
function conceptPanelTexts(cp) {
  if (typeof cp === 'string') return [cp];
  if (Array.isArray(cp)) return cp.map((e) => (typeof e === 'string' ? e : e && e.text));
  if (cp && typeof cp === 'object') return [cp.text];
  return [];
}

// The social block as the no-kit-NPC-names rule reads it: a conceptPanel array entry with a
// `condition` is left out, because only a learner who met that NPC sees it (owner ruling for ca12,
// D214/AC0, 20 Nov 2026). Every other part of the block, and every unconditional panel entry, is kept.
function socialForNameRule(social) {
  const copy = JSON.parse(JSON.stringify(social));
  const strings = copy && copy.awarenessEpisode && copy.awarenessEpisode.strings;
  if (strings && Array.isArray(strings.conceptPanel)) {
    strings.conceptPanel = strings.conceptPanel.filter((e) => !(e && typeof e === 'object' && 'condition' in e));
  }
  return JSON.stringify(copy);
}
const nameOffenders = (social, displayNames) => {
  const text = socialForNameRule(social);
  return displayNames.filter((n) => text.includes(n) || text.includes(n.split(' ')[0]));
};

// A chain shell invites through the chain, so no entry of its panel carries "have a word with".
function assertChainPanelNoInvite(cp, label) {
  const texts = conceptPanelTexts(cp);
  assert.ok(texts.length > 0 && texts.every((t) => typeof t === 'string' && t.length > 0), `${label}: every conceptPanel entry has text`);
  for (const t of texts) assert.ok(!/have a word with/.test(t), `${label}: a chain shell invites through the chain, not the panel text`);
}

// Folders whose files are pinned: every check shell (ca_pre_*, ca_post_*) and the annual shell.
function pinnedShells() {
  return readdirSync(scenarios, { withFileTypes: true })
    .filter((d) => d.isDirectory() && /^(ca_pre_|ca_post_|ca_annual_)/.test(d.name))
    .map((d) => d.name)
    .sort();
}

// Every pinned file currently on disk, as repo-relative path -> sha256.
function currentFiles() {
  const out = {};
  for (const name of pinnedShells()) {
    const dir = join(scenarios, name);
    for (const f of ['scenario.json.erb', 'mission.json']) {
      if (existsSync(join(dir, f))) out[`scenarios/${name}/${f}`] = sha(join(dir, f));
    }
    // any other top-level file (dungeon_graph.* is regenerated by the validator and not pinned) is a stray
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      if (e.name === 'ink' || /^dungeon_graph\./.test(e.name) || ['scenario.json.erb', 'mission.json'].includes(e.name)) continue;
      out[`scenarios/${name}/${e.name}${e.isDirectory() ? '/' : ''}`] = e.isDirectory() ? 'directory' : sha(join(dir, e.name));
    }
    // ink/ and anything below it, so a subfolder is listed (and fails the pin) instead of crashing sha()
    const walk = (rel) => {
      const abs = join(dir, rel);
      for (const e of readdirSync(abs, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
        if (e.isDirectory()) walk(`${rel}/${e.name}`);
        else out[`scenarios/${name}/${rel}/${e.name}`] = sha(join(abs, e.name));
      }
    };
    if (existsSync(join(dir, 'ink'))) walk('ink');
  }
  for (const f of readdirSync(rooms).sort()) {
    if (/^room_aw_.*\.(json|tmj)$/.test(f)) out[`public/break_escape/assets/rooms/${f}`] = sha(join(rooms, f));
  }
  return out;
}

