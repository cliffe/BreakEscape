      objects: tr.objects.filter((o) => o.id.startsWith('kit_')),
      globals: Object.fromEntries(Object.entries(sc.globalVariables).filter(([k]) => k.startsWith('kit_'))),
      mappings: (hostOf(sc).eventMappings || []).filter(isKitMapping),
