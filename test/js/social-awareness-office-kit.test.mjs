const isKitMapping = (m) => Object.keys(m.setGlobal || {}).some((k) => k.startsWith('kit_')) ||
  KIT_NAME.test(String(m.condition || '')) || KIT_NAME.test(String(m.knot || '')) || KIT_NAME.test(String(m.targetKnot || ''));
