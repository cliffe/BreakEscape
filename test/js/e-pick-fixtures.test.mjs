// EXPECTED was recorded from interactions.js at d18d6516a (before the move) over these fixtures; the same fixtures run
// through the current E must give the same picks. EPICK_RECORD=1 prints a fresh table; EPICK_OLD=<path> loads another
// interactions.js. Run with: node test/js/e-pick-fixtures.test.mjs
import { writeFileSync } from 'node:fs';
import test from 'node:test';
import assert from 'node:assert/strict';
import { loadHarness } from './fixtures/label-e-harness.mjs';
import { handScenes, randomScenes } from './fixtures/label-e-scenes.mjs';

const h = await loadHarness({ oldLabel: undefined });
const scenes = [...handScenes, ...randomScenes()];

const table = [];
for (const s of scenes) {
    h.setRooms(s.build());
    for (const [fx, fy, dir] of s.stances) table.push(`${s.name} @${fx},${fy} ${dir}: ${h.pressE(fx, fy, dir)}`);
}

test('E picks over the fixtures match the recorded picks', () => {
    if (process.env.EPICK_RECORD) { writeFileSync(process.env.EPICK_RECORD, JSON.stringify(table, null, 1)); return; }
    assert.equal(table.length, EXPECTED.length);
    table.forEach((line, i) => assert.equal(line, EXPECTED[i]));
});

